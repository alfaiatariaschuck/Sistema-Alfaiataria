-- Importação da lista histórica de vendas (planilha pessoal do dono, desde
-- o início do negócio) — alimenta a nova aba de filtro de clientes e a
-- campanha de reativação em Clientes.jsx (quantidade comprada, ano da
-- última compra, se já recomprou). Não mexe em pedidos/peças reais: os
-- dados aqui são só "nome + quantidade + ano", sem medidas, pagamento ou
-- status de produção — misturar isso nas tabelas de produção (pedidos,
-- pedidos_alfaiataria) inventaria campos que a planilha antiga não tinha.
-- ADITIVO: pode rodar uma vez só (os dois inserts abaixo são idempotentes
-- na parte de clientes via ON CONFLICT; a parte de historico_vendas usa
-- uma trava por já ter sido importada, ver o "delete from" condicional).

create table if not exists historico_vendas (
  id uuid primary key default gen_random_uuid(),
  cliente_id uuid not null references clientes(id) on delete cascade,
  cliente_nome text not null,
  quantidade integer not null,
  ano integer not null,
  recompra boolean not null default false,
  criado_em timestamptz not null default now()
);

create index if not exists historico_vendas_cliente_id_idx on historico_vendas (cliente_id);

alter table historico_vendas enable row level security;

drop policy if exists "authenticated_full_access" on historico_vendas;
create policy "authenticated_full_access" on historico_vendas
  for all to authenticated using (true) with check (true);

